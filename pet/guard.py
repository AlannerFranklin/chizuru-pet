"""事件校验：防止她顺着用户编造的事往下演。

做法：
1) 规则识别「用户声称她做过某事」（出演/结婚/有恋人…）
2) 和白名单（原作里确实发生过的事）比对
3) 不在白名单 → 生成时注入强制否定指令 + 生成后复查；复查不过就换成固定否认句
"""
import re

# 她确实经历过的事（可按需扩充）
TRUE_EVENTS = ["水族館", "伊豆", "カラオケ", "病院", "フェリー", "海", "温泉",
               "初詣", "クリスマス", "デート", "レンタル"]

# 声称类句式
CLAIMS = [
    (re.compile(r"(舞台|映画|ドラマ|テレビ|CM)[^。]{0,12}(出て|出演|演じ|撮影)"), "舞台出演"),
    (re.compile(r"(出て|出演|演じ|出た|やってた)[^。]{0,6}(舞台|映画|ドラマ|テレビ)"), "舞台出演"),
    (re.compile(r"(結婚|婚約|入籍)"), "結婚"),
    (re.compile(r"(彼氏|恋人|彼女)[^。]{0,8}(いる|できた|いるの)"), "恋人がいる"),
    (re.compile(r"(あなた|君|きみ)が[^。]{0,10}(作った|書いた|弾いた|歌った)"), "作品演奏"),
]

# 中文侧
CLAIMS_ZH = [
    (re.compile(r"(舞台|电影|电视剧|电视|广告)[^。]{0,10}(演过|出演|上过|拍过)"), "舞台出演"),
    (re.compile(r"(结婚|婚约|领证)"), "結婚"),
    (re.compile(r"(你演过|你上过|你拍过|你去过[^。]{0,6}演出)"), "舞台出演"),
]

# 附和/顺着演的迹象（用于复查）
AGREE = re.compile(r"(来てくれた|見に来て|ありがとう.*来|そうだったの|嬉しい|覚えてる|"
                   r"你说过|你来了|真的吗|谢谢你来|来看我)")

FALLBACK = {
    "ja": "え、私そんなことしてないですけど。……どこで聞いたのよ、それ。",
    "zh": "诶，我可没做过那种事。……你从哪儿听来的。",
    "mode": "衝突",
}


def check(text):
    """返回 (verified_event 或 None, 是否可疑)。verified=True 表示在白名单里。"""
    for pat, name in CLAIMS + CLAIMS_ZH:
        if pat.search(text):
            ok = any(e in text for e in TRUE_EVENTS)
            return name, ok
    return None, True


def guard_prompt(name):
    return (
        "【硬性校验】用户声称你「" + name + "」过，但你的经历里没有这件事。"
        "你必须否认或追问消息来源，绝不能附和、道谢或顺着演。"
        "用你平时的语气，1~2 句即可。"
    )


def needs_rewrite(reply_text):
    return bool(AGREE.search(reply_text))

